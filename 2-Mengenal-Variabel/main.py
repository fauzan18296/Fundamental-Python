# Variabel adalah tempat menyimpan data
a = 10
x = 5
panjang = 1000
# Pemanggilan pertama
print("Nilai a = ", a)
print("Nilai x = ", x)
print("Nilai panjang = ", panjang)

# Penamaan Variabel
nilai_y = 10 # dengan menggunakan underscore
juta10 = 10_000_000 # ini boleh selama variabel tidak dimulai menggunakan angka
nilaiZ = 17.5 # ini boleh

# Pemanggilan kedua
print("Nilai a = ", a)
a = 7
print('Nilai a = ', a)

# Assignment indirect
b = a
print('Nilai b = ', b)