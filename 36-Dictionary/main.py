# List -> array, mengakses dengan menggunakan index
data_list = ['ucup', 'otong', 'dudung']

print(data_list[0])

# Dictionary (Dict) -> Associative Array
# Identifier -> Key
data_dict = {
  'key' : 'value',
  'cp' : 'ucup',
  'tg' : 'otong',
  'dg' : 'dudung',
  'number' : 100,
  'list' : data_list
}
print(data_dict['tg'])
print(data_dict['number'])
print(data_dict['list'])